#!/usr/bin/env python3
"""Install the zh/fr + HUD translation layer into Unity builds.

  python3 scripts/unity/oiyo-i18n/install.py [build ...]

For each tables/<build>.json: copies OiyoI18n.cs into the build's Runtime folder,
writes OiyoI18nTable.cs (the table as C#), adds .meta files, and makes the build's
scripts/build-fonts.py also pull Simplified Chinese glyphs (Noto Sans SC).
Fails when a U("...") / F("...") / OiyoI18n.En("...") string in the build's
code has no row, or a U/F row lacks a language.
"""
import glob, hashlib, json, re, shutil, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
ORDER = ["ko", "ja", "es", "zh", "fr"]
LIT = r'"((?:[^"\\]|\\.)*)"'

def cs_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"' if s is not None else 'null'

def unescape(s):
    return s.encode('utf-8').decode('unicode_escape').encode('latin-1').decode('utf-8')

def meta(path, body):
    m = path.with_name(path.name + '.meta')
    if not m.exists():
        guid = hashlib.md5(('oiyo-i18n:' + str(path.relative_to(ROOT))).encode()).hexdigest()
        m.write_text(f"fileFormatVersion: 2\nguid: {guid}\n{body}")

MONO = "MonoImporter:\n  externalObjects: {}\n  serializedVersion: 2\n  defaultReferences: []\n  executionOrder: 0\n  icon: {instanceID: 0}\n  userData: \n  assetBundleName: \n  assetBundleVariant: \n"

def install(build):
    table = json.loads((HERE / 'tables' / f'{build}.json').read_text(encoding='utf-8'))
    table.pop('_order', None)
    runtime_files = [Path(p) for p in glob.glob(str(ROOT / 'prototypes' / build / 'Assets' / '*' / 'Runtime' / '*.cs'))]
    players = [p for p in runtime_files if not p.name.startswith('Oiyo')]
    if not players:
        return [f'{build}: no Runtime/*.cs']
    runtime = players[0].parent
    errors = []
    src = ''.join(p.read_text(encoding='utf-8') for p in players)
    full = set()
    for m in re.finditer(r'\b(?:U|F)\(\s*' + LIT, src):
        full.add(unescape(m.group(1)))
    en_only = set(unescape(m.group(1)) for m in re.finditer(r'OiyoI18n\.En\(\s*' + LIT, src))
    for key in sorted(full):
        row = table.get(key)
        if row is None: errors.append(f'{build}: no row for U/F {key!r}')
        elif any(not row[i] for i in range(5)): errors.append(f'{build}: U/F row {key!r} lacks a language')
    for key in sorted(en_only):
        row = table.get(key)
        if row is None or not row[3] or not row[4]: errors.append(f'{build}: no zh/fr for {key!r}')
    for key, row in table.items():
        if len(row) != 5: errors.append(f'{build}: row {key!r} needs 5 entries')
    if errors:
        return errors
    shutil.copyfile(HERE / 'OiyoI18n.cs', runtime / 'OiyoI18n.cs')
    meta(runtime / 'OiyoI18n.cs', MONO)
    lines = ['// Generated by scripts/unity/oiyo-i18n/install.py from tables/%s.json. Do not edit.' % build,
             'using System.Collections.Generic;', '', 'public static partial class OiyoI18n', '{',
             '    // English -> { ko, ja, es, zh, fr }; null keeps the game\'s own text.',
             '    static readonly Dictionary<string, string[]> Table = new Dictionary<string, string[]>', '    {']
    for key, row in table.items():
        lines.append(f'        [{cs_str(key)}] = new string[] {{ {", ".join(cs_str(x) for x in row)} }},')
    lines += ['    };', '}', '']
    (runtime / 'OiyoI18nTable.cs').write_text('\n'.join(lines), encoding='utf-8')
    meta(runtime / 'OiyoI18nTable.cs', MONO)
    fonts = ROOT / 'prototypes' / build / 'scripts' / 'build-fonts.py'
    if fonts.exists():
        t = fonts.read_text(encoding='utf-8')
        if "'Noto Sans SC'" not in t:
            a = "['Noto Sans JP', 'Noto Sans Symbols 2', 'Noto Sans Symbols']"
            if a in t:
                fonts.write_text(t.replace(a, "['Noto Sans JP', 'Noto Sans SC', 'Noto Sans Symbols 2', 'Noto Sans Symbols']"), encoding='utf-8')
            else:
                errors.append(f'{build}: build-fonts.py family list not found, add Noto Sans SC by hand')
    return errors

def main():
    builds = sys.argv[1:] or sorted(p.stem for p in (HERE / 'tables').glob('*.json'))
    bad = []
    for b in builds:
        e = install(b)
        print(('FAIL ' if e else 'ok   ') + b)
        bad += e
    for e in bad: print('  ' + e)
    return 1 if bad else 0

if __name__ == '__main__':
    sys.exit(main())
