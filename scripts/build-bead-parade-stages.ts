/**
 * Builds the 30 Bead Parade parades (src/lib/games/bead-parade.ts buildStage) and writes them to
 * src/lib/games/bead-parade-stages.ts. Each parade is played by a greedy shooter, whose
 * shots become its plan, and checked against the human-like and random shooters while it is built, which takes a
 * few minutes — too slow to do on every page load.
 * Usage: npx tsx scripts/build-bead-parade-stages.ts
 */
import { writeFileSync } from "node:fs";
import { STAGE_COUNT, buildStage } from "../src/lib/games/bead-parade";

const rows: string[] = [];
for (let i = 0; i < STAGE_COUNT; i++) {
  const st = buildStage(i);
  rows.push(`  ${JSON.stringify(st)},`);
  console.log(`stage ${i + 1}: ${st.beads.length} beads, ${st.colors} colours, ${st.plan.length} shots`);
}
writeFileSync(
  new URL("../src/lib/games/bead-parade-stages.ts", import.meta.url),
  `// Generated by scripts/build-bead-parade-stages.ts from src/lib/games/bead-parade.ts. Do not edit.\nimport type { BeadStage } from "./bead-parade";\n\nexport const BEAD_STAGES: BeadStage[] = [\n${rows.join("\n")}\n];\n`,
);
