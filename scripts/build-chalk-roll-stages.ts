/**
 * Builds the 30 Chalk Roll boards (src/lib/games/chalk-roll.ts buildStage) and writes them to
 * src/lib/games/chalk-roll-stages.ts. Each board is searched for a line that lands the marble and checked against
 * the shaky and random drawers while it is built, which takes a while — too slow to do on every page load.
 * Usage: npx tsx scripts/build-chalk-roll-stages.ts
 */
import { writeFileSync } from "node:fs";
import { STAGE_COUNT, buildStage } from "../src/lib/games/chalk-roll";

const rows: string[] = [];
for (let i = 0; i < STAGE_COUNT; i++) {
  const st = buildStage(i);
  rows.push(`  ${JSON.stringify(st)},`);
  console.log(`stage ${i + 1}: par ${st.par}, ink ${st.ink}, ${st.walls.length} ledges, ${st.tacks.length} tacks`);
}
writeFileSync(
  new URL("../src/lib/games/chalk-roll-stages.ts", import.meta.url),
  `// Generated by scripts/build-chalk-roll-stages.ts from src/lib/games/chalk-roll.ts. Do not edit.\nimport type { ChalkStage } from "./chalk-roll";\n\nexport const CHALK_STAGES: ChalkStage[] = [\n${rows.join("\n")}\n];\n`,
);
