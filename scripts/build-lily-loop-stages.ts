/**
 * Builds the 30 Lily Loop ponds (src/lib/games/lily-loop.ts buildStage) and writes them to
 * src/lib/games/lily-loop-stages.ts. Each pond is searched for sends that clear it and
 * checked against the human-like and random keepers while it is built, which takes a while — too slow to do on every
 * page load.
 * Usage: npx tsx scripts/build-lily-loop-stages.ts
 */
import { writeFileSync } from "node:fs";
import { STAGE_COUNT, buildStage } from "../src/lib/games/lily-loop";

const rows: string[] = [];
for (let i = 0; i < STAGE_COUNT; i++) {
  const st = buildStage(i);
  rows.push(`  ${JSON.stringify(st)},`);
  console.log(`stage ${i + 1}: ${st.rows}×${st.cols}, ${st.colors.length} colours, ${st.lanes.flat().length} frogs, ${st.pads} pads, par ${st.par}`);
}
writeFileSync(
  new URL("../src/lib/games/lily-loop-stages.ts", import.meta.url),
  `// Generated by scripts/build-lily-loop-stages.ts from src/lib/games/lily-loop.ts. Do not edit.\nimport type { LilyStage } from "./lily-loop";\n\nexport const LILY_STAGES: LilyStage[] = [\n${rows.join("\n")}\n];\n`,
);
