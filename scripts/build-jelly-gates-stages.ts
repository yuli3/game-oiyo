/**
 * Builds the 30 Jelly Gates trays (src/lib/games/jelly-gates.ts buildStage) and writes them to
 * src/lib/games/jelly-gates-stages.ts. Each tray is built backwards from an empty one and checked against the
 * careful, human-like and random players, which takes a few minutes — too slow to do on every page load.
 * Usage: npx tsx scripts/build-jelly-gates-stages.ts
 */
import { writeFileSync } from "node:fs";
import { STAGE_COUNT, buildStage } from "../src/lib/games/jelly-gates";

const rows: string[] = [];
for (let i = 0; i < STAGE_COUNT; i++) {
  const st = buildStage(i);
  rows.push(`  ${JSON.stringify(st)},`);
  console.log(`stage ${i + 1}: ${st.cols}x${st.rows}, ${st.blocks.length} blocks, par ${st.par}, limit ${st.limit}`);
}
writeFileSync(
  new URL("../src/lib/games/jelly-gates-stages.ts", import.meta.url),
  `// Generated by scripts/build-jelly-gates-stages.ts from src/lib/games/jelly-gates.ts. Do not edit.\nimport type { JellyStage } from "./jelly-gates";\n\nexport const JELLY_STAGES: JellyStage[] = [\n${rows.join("\n")}\n];\n`,
);
