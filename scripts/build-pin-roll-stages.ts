/**
 * Builds the 30 Pin Roll lanes (src/lib/games/pin-roll.ts buildStage) and writes them to
 * src/lib/games/pin-roll-stages.ts. Each lane is checked against the careful, human-like and random players
 * while it is built, which takes a few minutes — too slow to do on every page load.
 * Usage: npx tsx scripts/build-pin-roll-stages.ts
 */
import { writeFileSync } from "node:fs";
import { STAGE_COUNT, buildStage } from "../src/lib/games/pin-roll";

const rows: string[] = [];
for (let i = 0; i < STAGE_COUNT; i++) {
  const st = buildStage(i);
  rows.push(`  ${JSON.stringify(st)},`);
  console.log(`stage ${i + 1}: ${st.frames} frames, ${st.posts.length} posts, need ${st.need}, par ${st.par}`);
}
writeFileSync(
  new URL("../src/lib/games/pin-roll-stages.ts", import.meta.url),
  `// Generated by scripts/build-pin-roll-stages.ts from src/lib/games/pin-roll.ts. Do not edit.\nimport type { PinStage } from "./pin-roll";\n\nexport const PIN_STAGES: PinStage[] = [\n${rows.join("\n")}\n];\n`,
);
