/**
 * Builds the 30 Sunny Pots rooms (src/lib/games/sunny-pots.ts buildStage) and writes them to
 * src/lib/games/sunny-pots-stages.ts. Each room is pulled apart from its solved
 * state, searched breadth-first for its fewest moves and checked against the human-like and random gardeners while it
 * is built, which takes a while — too slow to do on every page load.
 * Usage: npx tsx scripts/build-sunny-pots-stages.ts
 */
import { writeFileSync } from "node:fs";
import { STAGE_COUNT, buildStage } from "../src/lib/games/sunny-pots";

const rows: string[] = [];
for (let i = 0; i < STAGE_COUNT; i++) {
  const st = buildStage(i);
  rows.push(`  ${JSON.stringify(st)},`);
  console.log(`stage ${i + 1}: ${st.w}×${st.h}, ${st.pots.length} pots, par ${st.par}`);
}
writeFileSync(
  new URL("../src/lib/games/sunny-pots-stages.ts", import.meta.url),
  `// Generated by scripts/build-sunny-pots-stages.ts from src/lib/games/sunny-pots.ts. Do not edit.\nimport type { PotStage } from "./sunny-pots";\n\nexport const POTS_STAGES: PotStage[] = [\n${rows.join("\n")}\n];\n`,
);
