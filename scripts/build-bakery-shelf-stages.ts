/**
 * Builds the 30 Bakery Shelf deals (src/lib/games/bakery-shelf.ts buildStage) and writes them to
 * src/lib/games/bakery-shelf-stages.ts. Each deal is searched for a way to sell out and checked against the human-like
 * and random shoppers while it is built, which takes a while — too slow to do on every page load.
 * Usage: npx tsx scripts/build-bakery-shelf-stages.ts
 */
import { writeFileSync } from "node:fs";
import { STAGE_COUNT, buildStage } from "../src/lib/games/bakery-shelf";

const rows: string[] = [];
for (let i = 0; i < STAGE_COUNT; i++) {
  const st = buildStage(i);
  rows.push(`  ${JSON.stringify(st)},`);
  console.log(`stage ${i + 1}: ${st.shelves.length} shelves, par ${st.par}, limit ${st.limit}`);
}
writeFileSync(
  new URL("../src/lib/games/bakery-shelf-stages.ts", import.meta.url),
  `// Generated by scripts/build-bakery-shelf-stages.ts from src/lib/games/bakery-shelf.ts. Do not edit.\nimport type { ShelfStage } from "./bakery-shelf";\n\nexport const SHELF_STAGES: ShelfStage[] = [\n${rows.join("\n")}\n];\n`,
);
