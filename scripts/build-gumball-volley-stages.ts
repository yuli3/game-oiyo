/**
 * Builds the 30 Gumball Volley shops (src/lib/games/gumball-volley.ts buildStage) and writes them to
 * src/lib/games/gumball-volley-stages.ts. Each shop is checked against the careful, human-like and random players
 * while it is built, which takes a few minutes — too slow to do on every page load.
 * Usage: npx tsx scripts/build-gumball-volley-stages.ts
 */
import { writeFileSync } from "node:fs";
import { STAGE_COUNT, buildStage } from "../src/lib/games/gumball-volley";

const rows: string[] = [];
for (let i = 0; i < STAGE_COUNT; i++) {
  const st = buildStage(i);
  rows.push(`  ${JSON.stringify(st)},`);
  console.log(`stage ${i + 1}: ${st.rows.length} rows, par ${st.par}`);
}
writeFileSync(
  new URL("../src/lib/games/gumball-volley-stages.ts", import.meta.url),
  `// Generated by scripts/build-gumball-volley-stages.ts from src/lib/games/gumball-volley.ts. Do not edit.\nimport type { VolleyStage } from "./gumball-volley";\n\nexport const VOLLEY_STAGES: VolleyStage[] = [\n${rows.join("\n")}\n];\n`,
);
