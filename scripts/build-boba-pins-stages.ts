/**
 * Builds the 30 Boba Pins machines (src/lib/games/boba-pins.ts buildStage) and writes them to
 * src/lib/games/boba-pins-stages.ts. Each machine is searched for the fewest pins to pull and checked against
 * the careful and random players while it is built, which takes a while — too slow to do on every page load.
 * Usage: npx tsx scripts/build-boba-pins-stages.ts
 */
import { writeFileSync } from "node:fs";
import { STAGE_COUNT, buildStage } from "../src/lib/games/boba-pins";

const rows: string[] = [];
for (let i = 0; i < STAGE_COUNT; i++) {
  const st = buildStage(i);
  rows.push(`  ${JSON.stringify(st)},`);
  console.log(`stage ${i + 1}: ${st.pins.length} pins, pull ${st.plan.join(" ")}`);
}
writeFileSync(
  new URL("../src/lib/games/boba-pins-stages.ts", import.meta.url),
  `// Generated by scripts/build-boba-pins-stages.ts from src/lib/games/boba-pins.ts. Do not edit.\nimport type { BobaStage } from "./boba-pins";\n\nexport const BOBA_STAGES: BobaStage[] = [\n${rows.join("\n")}\n];\n`,
);
