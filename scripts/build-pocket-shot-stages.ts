/**
 * Builds the 30 Pocket Shot tables (src/lib/games/pocket-shot.ts buildStage) and writes them to
 * src/lib/games/pocket-shot-stages.ts. Each table is checked against the careful, human-like and random players
 * while it is built, which takes about a minute — too slow to do on every page load.
 * Usage: npx tsx scripts/build-pocket-shot-stages.ts
 */
import { writeFileSync } from "node:fs";
import { STAGE_COUNT, buildStage } from "../src/lib/games/pocket-shot";

const rows: string[] = [];
for (let i = 0; i < STAGE_COUNT; i++) {
  const st = buildStage(i);
  rows.push(`  { stage: ${st.stage}, balls: ${JSON.stringify(st.balls)}, cue: ${JSON.stringify(st.cue)}, shots: ${st.shots}, par: ${st.par} },`);
  console.log(`stage ${i + 1}: ${st.balls.length} balls, ${st.shots} shots, par ${st.par}`);
}
writeFileSync(
  new URL("../src/lib/games/pocket-shot-stages.ts", import.meta.url),
  `// Generated by scripts/build-pocket-shot-stages.ts from src/lib/games/pocket-shot.ts. Do not edit.\nimport type { PoolStage } from "./pocket-shot";\n\nexport const POOL_STAGES: PoolStage[] = [\n${rows.join("\n")}\n];\n`,
);
